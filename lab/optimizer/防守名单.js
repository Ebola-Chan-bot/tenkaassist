'use strict';
/*
 * 防守名单（剪枝A 的静态数据源）——按队伍构成判定"哪些槽位的방(防守)可以在搜索中剪掉"。
 *
 * ## 为什么能剪（实证依据，详见 session plan 实验5~9/14）
 * 打桩环境下 방(act_defense) 本身伤害为 0、且不改 CD，其价值只可能来自两类机制：
 *   (a) 角色自身的防守触发/自定义防守钩子 —— 50 个"有防守机制"角色；
 *   (b) 队友授予的"防守时触发"增益 buff（如 닌저10163 给全队挂"방时→增伤"）—— 12 个"授予者"角色。
 * 关键结论：방价值是**队级涌现属性**，不能按角色静态判定。逐层实证（实验7/9，正规先验前瞻贪心）：
 *   - 层0（队内无任何50名单角色）：全队방皆空放 → 无机制角色 방→평 **零有损**（94点全持平/更优）。
 *   - 层1（含50名单角色、但无12授予者）：无机制角色的방无人响应 → 방→평 **零有损**；且前瞻贪心本就不会给它选방。
 *   - 层2（含12授予者之一）：授予者把"방响应buff"挂到队友身上，**无机制队友的방也会触发授予者的增伤** → 有损（49点中27点=46%），**不可剪**。
 * 因此剪枝规则：队内不含任何授予者时，禁掉"无防守机制角色"的방（层0→等价整队禁방；层1→只禁无机制캐，50名单캐的방保留）。
 *
 * ## 数据安全（不破坏渐近完备性）
 * 本剪枝只作用于**束搜索的候选枚举**与**先验前瞻贪心的候选枚举/rollout填充**。
 * 后置的 爬山（单token改动作邻域含방）与 编辑球层（全空间枚举）不受影响，可把被剪的방路径重新搜回 →
 *   最终解空间仍渐近完备；剪枝只影响"受限时间/预算下的命中率"，与 序先验.js 同性质（软加速，非硬裁剪）。
 * 另设总开关 设置.禁防守剪枝（默认 true），传 false 完全关闭，回到全방枚举。
 *
 * ## 名单来源与重算
 * 两份清单由 机制表/生成/*.json（191角色数据化收官态）扫描得出，经动态实验逐层验证：
 *   - 有防守机制(50)：bang触发35 ∪ haengdong触发13 ∪ defense钩子非默认17，去重。扫描见 _名单精算.js / _防守特征表.js。
 *   - 授予者(12)：给"非self"目标挂响应방的增益 buff（已排除 <방한의힘>=防寒 等假阳性）。扫描见 _방CD扫描.js / 实验6块C。
 * 机制表新增/变更角色后，用上述脚本重算并更新下方两个数组（授予者必须⊆有防守机制，已验证）。
 */

// 50 个"有防守机制"角色：其 방 对自身有触发价值，任何队伍中都必须保留其 방 分支。
const 有防守机制清单 = [
  10005, 10007, 10008, 10022, 10023, 10028, 10040, 10044, 10050, 10056,
  10062, 10074, 10082, 10083, 10094, 10096, 10111, 10114, 10116, 10127,
  10130, 10138, 10140, 10144, 10147, 10149, 10153, 10154, 10155, 10160,
  10163, 10164, 10166, 10170, 10171, 10173, 10179, 10181, 10183, 10186,
  10192, 10193, 10196, 10197, 10198, 10200, 10201, 10202, 10206, 10207,
];

// 12 个"授予者"角色：给队友挂"방时触发"增益 buff。队内含任一授予者 → 整队不剪방（层2）。
const 授予者清单 = [
  10023, 10040, 10050, 10062, 10138, 10144, 10149, 10163, 10183, 10193, 10201, 10207,
];

const 有防守机制集 = new Set(有防守机制清单);
const 授予者集 = new Set(授予者清单);

// 自检：授予者必须全部⊆有防守机制（实验6已验证"授予他人但不在50名单内: 无"）。启动时兜底断言。
for (const id of 授予者清单) {
  if (!有防守机制集.has(id)) throw new Error(`防守名单自检失败: 授予者 ${id} 不在有防守机制集内，名单已漂移，请用 _名单精算.js/_방CD扫描.js 重算`);
}

function 有防守机制(id) { return 有防守机制集.has(id); }
function 是授予者(id) { return 授予者集.has(id); }

// 队伍分层：0=无50名单角色(可整队剪방) 1=有名单无授予者(可剪无机制캐방) 2=有授予者(不可剪)
function 分层(ids) {
  if (ids.some(i => 授予者集.has(i))) return 2;
  if (ids.some(i => 有防守机制集.has(i))) return 1;
  return 0;
}

/*
 * 计算每个槽位是否【禁用防守】。返回长度5的布尔数组，禁用防守[i]=true 表示槽位 i 的 방(防守) 在搜索中可剪。
 * 规则：队内含任一授予者 → 全 false（层2不剪）；否则 → 该槽位角色"无防守机制"时 true。
 * 在搜索入口算一次，候选枚举时用 `if (禁用防守[i] && act==='방') continue` 落地。
 */
function 计算禁用防守(ids) {
  const 有授予者 = ids.some(i => 授予者集.has(i));
  return ids.map(id => !有授予者 && !有防守机制集.has(id));
}

module.exports = {
  有防守机制清单, 授予者清单, 有防守机制集, 授予者集,
  有防守机制, 是授予者, 分层, 计算禁用防守,
};
